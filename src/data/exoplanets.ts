export function getHabitablePlanets(): Exoplanet[] {
  return EXOPLANETS.filter(p => p.habitabilityZone !== "none");
}

export function getNearbyPlanets(maxLy: number = 50): Exoplanet[] {
  return EXOPLANETS.filter(p => p.distanceLy <= maxLy);
}

export function getEarthSimilarPlanets(): Exoplanet[] {
  return EXOPLANETS.filter(p => 
    p.radiusEarth >= 0.8 && p.radiusEarth <= 1.5 && 
    p.habitabilityZone !== "none"
  );
}

